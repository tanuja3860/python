from sklearn.linear_model import LogisticRegression
from sklearn.metrics import confusion_matrix, accuracy_score, precision_score, recall_score, f1_score
import numpy as np
X_train = np.array([[45], [48], [50], [55], [60], [65], [70]])
y_train = np.array([0, 0, 0, 1, 1, 1, 1])
model = LogisticRegression()
model.fit(X_train, y_train)
X_test = np.array([[46], [49], [51], [54], [58], [62], [68]])
y_true = np.array([0, 0, 1, 1, 1, 1, 1])
y_pred = model.predict(X_test)
tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
accuracy = accuracy_score(y_true, y_pred)
precision = precision_score(y_true, y_pred)
recall = recall_score(y_true, y_pred)
f1 = f1_score(y_true, y_pred)
print("--- Confusion Matrix Breakdown ---")
print(f"True Negatives (TN) : {tn}")
print(f"False Positives (FP): {fp} <- (Model said 'Go' but should be 'Stop')")
print(f"False Negatives (FN): {fn} <- (Model said 'Stop' but should be 'Go')")
print(f"True Positives (TP) : {tp}")
print("-" * 34)
print(f"Accuracy  : {accuracy:.2%}")
print(f"Precision : {precision:.2%}")
print(f"Recall    : {recall:.2%}")
print(f"F1-Score  : {f1:.2%}")